package ops

import (
	"context"
	"testing"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/s3"

	"goodkind.io/tack/internal/config"
	"goodkind.io/tack/internal/testenv"
)

// backupTestStore uses a separate bucket on the test SeaweedFS engine. The
// test setup originally used the release then running in production.
// Tests create and inspect objects through the production S3 client and
// helpers.
type backupTestStore struct {
	t      *testing.T
	bucket testenv.ObjectStoreBucket
	client *s3.Client
	// stopped is true between stop and start.
	stopped bool
}

// newBackupTestStore creates an empty bucket and writes objects (key to body)
// into it.
func newBackupTestStore(t *testing.T, objects map[string][]byte) *backupTestStore {
	t.Helper()
	backupS3Attempts(t, backupS3DefaultMaxAttempts)
	store := &backupTestStore{t: t, bucket: testenv.ObjectStore(t), client: nil, stopped: false}
	store.client = newBackupS3Client(store.config())

	for key, body := range objects {
		store.put(key, body)
	}

	return store
}

// config returns a new configuration for reading and writing the bucket
// with the permitted identity.
func (s *backupTestStore) config() *config.Config {
	return &config.Config{
		BackupS3Endpoint:   s.bucket.Endpoint,
		BackupS3AccessKey:  s.bucket.AccessKey, // gitleaks:allow key generated by the test engine
		BackupS3SecretKey:  s.bucket.SecretKey,
		BackupS3Region:     s.bucket.Region,
		BackupS3BucketMain: s.bucket.Bucket,
	}
}

// signAsReader switches cfg to the identity that can read and list the
// bucket. The engine refuses writes from that identity with AccessDenied.
func (s *backupTestStore) signAsReader(cfg *config.Config) {
	cfg.BackupS3AccessKey = s.bucket.ReadOnlyAccessKey // gitleaks:allow key generated by the test engine
	cfg.BackupS3SecretKey = s.bucket.ReadOnlySecretKey
}

// signAsWriter switches cfg back to the identity that may write.
func (s *backupTestStore) signAsWriter(cfg *config.Config) {
	cfg.BackupS3AccessKey = s.bucket.AccessKey // gitleaks:allow key generated by the test engine
	cfg.BackupS3SecretKey = s.bucket.SecretKey
}

// put writes body under key.
func (s *backupTestStore) put(key string, body []byte) {
	s.t.Helper()
	if err := putObjectBytes(
		context.Background(),
		s.client,
		s.bucket.Bucket,
		key,
		body,
	); err != nil {
		s.t.Fatalf("put %s: %v", key, err)
	}
}

// remove deletes the object under key.
func (s *backupTestStore) remove(key string) {
	s.t.Helper()
	_, err := s.client.DeleteObject(
		context.Background(),
		&s3.DeleteObjectInput{
			Bucket: aws.String(s.bucket.Bucket),
			Key:    aws.String(key),
		},
	)
	if err != nil {
		s.t.Fatalf("delete %s: %v", key, err)
	}
}

// object reads the object under key. It returns found as false when the key
// is absent.
func (s *backupTestStore) object(key string) (body []byte, found bool) {
	s.t.Helper()
	body, err := getObjectBytes(context.Background(), s.client, s.bucket.Bucket, key)
	if isObjectNotFound(err) {
		return nil, false
	}

	if err != nil {
		s.t.Fatalf("get %s: %v", key, err)
	}

	return body, true
}

// stop stops the bucket's engine. The endpoint refuses connections, and the
// engine preserves the bucket on disk. Callers defer ensureStarted to
// restart the engine before later tests use it.
func (s *backupTestStore) stop() {
	s.t.Helper()
	testenv.StopObjectStore(s.t, s.bucket.Container)
	s.stopped = true
	backupS3Attempts(s.t, 1)
}

// start restarts the engine and returns its endpoint.
func (s *backupTestStore) start() string {
	s.t.Helper()
	s.bucket.Endpoint = testenv.StartObjectStore(s.t, s.bucket.Container)
	s.stopped = false
	backupS3Attempts(s.t, backupS3DefaultMaxAttempts)
	s.client = newBackupS3Client(s.config())

	return s.bucket.Endpoint
}

// ensureStarted starts the engine again if the test left it stopped.
func (s *backupTestStore) ensureStarted() {
	s.t.Helper()
	if s.stopped {
		s.start()
	}
}

// getBytes reads key through the production reader and returns the engine's
// missing-key error. Its signature matches the getter that marker and
// version-log readers accept.
func (s *backupTestStore) getBytes(key string) ([]byte, error) {
	return getObjectBytes(context.Background(), s.client, s.bucket.Bucket, key)
}

// putBytes writes key through the production writer. Its signature matches
// the putter that marker and version-log writers accept.
func (s *backupTestStore) putBytes(key string, body []byte) error {
	return putObjectBytes(context.Background(), s.client, s.bucket.Bucket, key, body)
}

// versionLogGetter returns the production getter for the FoundationDB
// version record. The getter uses the record's own read limit.
func (s *backupTestStore) versionLogGetter() func(key string) ([]byte, error) {
	return fdbVersionLogGetter(context.Background(), s.client, s.bucket.Bucket)
}
